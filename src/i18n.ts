void CAT_KEYS;

export function fill(template: string, x: string | number, y?: string | number) {
  return template.replace("{x}", String(x)).replace("{y}", String(y ?? ""));
}

const STORAGE_KEY = "dof-lang";

export function loadLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v && v in DICT) return v as Lang;
  } catch {
    /* storage unavailable */
  }
  try {
    const nav = navigator.language.slice(0, 2).toLowerCase();
    if (nav in DICT) return nav as Lang;
  } catch {
    /* navigator unavailable */
  }
  return "en";
}

export function saveLang(lang: Lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* storage unavailable */
  }
}
